  static List<SubjectFolder> defaultFolders(String ownerId) {
    const names = [
      'Mathematics',
      'Science',
      'English',
      'History',
      'Computer Science',
      'Languages',
    ];
    const icons = ['chart', 'flask', 'book', 'history', 'code', 'language'];
    return List.generate(
      names.length,
      (i) => SubjectFolder(
        id: newId(),
        ownerId: ownerId,
        name: names[i],
        colorValue: C.folderColors[i % C.folderColors.length],
        icon: icons[i],
        order: i,
      ),
    );
  }
